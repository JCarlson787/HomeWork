    public void makeQuestions(JButton b) {
        save();
        if (counter <= 0 && b == BtnPrev) {
            counter = 0;
        } else if (counter == 14 && b == BtnNext) {
            counter = 14;
            JOptionPane.showMessageDialog(rootPane, "That is the end, please press submit.");
        } else if (counter > 0 && b == BtnPrev) {
            counter--;
        } else {
            counter++;
        }
        TxtQues.setText(theQuestions.get(counter).getQues());
        LabNumQues.setText("Question " + (counter + 1) + " of 15");
        RBtnOp1.setText(theQuestions.get(counter).getOption1());
        RBtnOp2.setText(theQuestions.get(counter).getOption2());
        RBtnOp3.setText(theQuestions.get(counter).getOption3());
        RBtnOp4.setText(theQuestions.get(counter).getOption4());

    }

