    public void save() {
        if (RBtnOp1.isSelected()) {
            choices.add(RBtnOp1.getText());
        } else if (RBtnOp2.isSelected()) {
            choices.add(RBtnOp2.getText());
        } else if (RBtnOp3.isSelected()) {
            choices.add(RBtnOp3.getText());
        } else if (RBtnOp4.isSelected()) {
            choices.add(RBtnOp4.getText());
        }
    }

    public void saveBtnState() {
        try {
            FileWriter writ = new FileWriter("btnState.txt", true);
        if (RBtnOp1.isSelected()) {
            writ.write("RBtnOp1 " + String.valueOf(this.counter) + "\n");
            writ.close();
        } else if (RBtnOp2.isSelected()) {
            writ.write("RBtnOp2 " + String.valueOf(this.counter) + "\n");
            writ.close();
        } else if (RBtnOp3.isSelected()) {
            writ.write("RBtnOp3 " + String.valueOf(this.counter) + "\n");
            writ.close();
        } else {
            writ.write("RBtnOp4 " + String.valueOf(this.counter) + "\n");
            writ.close();
        }
        
        } catch (Exception e) {
        }
    }
    
    public void getBtnState() {
        String line;
        String[] lines;
        try {
            BufferedReader buff = new BufferedReader(new FileReader("btnState.txt"));
            
            while ((line = buff.readLine()) != null) {
                lines = line.split(" ");
                if (Integer.valueOf(lines[1]) == this.counter) {
                   JRadioButton RBtn = new JRadioButton(lines[0]);
                   RBtn.setSelected(true);
                }
            }
        } catch (Exception e) {
        }
    }
    
