    private void Btn1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Btn1MouseClicked
        // TODO add your handling code here:
        if (Btn1.getText().equals("")) {
            Btn1.setText(game.currentPlayer.getSymbol());
            game.switchPlayer();
            CurrPlay.setText(game.currentPlayer.getSymbol());
        } if (checkWinnerGUI("X")) {
            
            BtnYes.setVisible(true);
            BtnNo.setVisible(true);
            Ques.setVisible(true);
            Xwins.setText(String.valueOf(++count));
            LabelVic.setText("X wins");
            
        } else if (checkWinnerGUI("O")) {
            
            BtnYes.setVisible(true);
            BtnNo.setVisible(true);
            Ques.setVisible(true);
            Owins2.setText(String.valueOf(++countO)); 
            LabelVic.setText("O wins");
            
        } else if (full()) {
            
            LabelTies.setText(String.valueOf(++countTie));
            BtnYes.setVisible(true);
            BtnNo.setVisible(true);
            Ques.setVisible(true);
        }
    }//GEN-LAST:event_Btn1MouseClicked

