public boolean checkWinnerGUI(String symbol) {
        if (Btn7.getText().equals(symbol) && Btn8.getText().equals(symbol) && Btn9.getText().equals(symbol)) {
            return true;
        } else if (Btn4.getText().equals(symbol) && Btn5.getText().equals(symbol) && Btn6.getText().equals(symbol)) {
            return true;
        } else if (Btn1.getText().equals(symbol) && Btn2.getText().equals(symbol) && Btn3.getText().equals(symbol)) {
            return true;
        } else if (Btn7.getText().equals(symbol) && Btn4.getText().equals(symbol) && Btn1.getText().equals(symbol)) {
            return true;
        } else if (Btn8.getText().equals(symbol) && Btn5.getText().equals(symbol) && Btn2.getText().equals(symbol)) {
            return true;
        } else if (Btn9.getText().equals(symbol) && Btn6.getText().equals(symbol) && Btn3.getText().equals(symbol)) {
            return true;
        } else if (Btn7.getText().equals(symbol) && Btn5.getText().equals(symbol) && Btn3.getText().equals(symbol)) {
            return true;
        } else if (Btn9.getText().equals(symbol) && Btn5.getText().equals(symbol) && Btn1.getText().equals(symbol)) {
            return true;
        } else {
            return false;
        }
    }
